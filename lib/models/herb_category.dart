/// 药材分类枚举
enum HerbCategory {
  plant('植物类', 0.09),
  animal('动物类', 0.13),
  mineral('矿物类', 0.13);

  final String name;
  final double taxRate;

  const HerbCategory(this.name, this.taxRate);

  /// 根据药材名称查找分类
  static HerbCategory? findByHerbName(String herbName) {
    final trimmedName = herbName.trim();
    if (plantHerbs.contains(trimmedName)) return HerbCategory.plant;
    if (animalHerbs.contains(trimmedName)) return HerbCategory.animal;
    if (mineralHerbs.contains(trimmedName)) return HerbCategory.mineral;
    return null;
  }

  /// 根据药材名称获取税率
  static double? getTaxRateByHerbName(String herbName) {
    return findByHerbName(herbName)?.taxRate;
  }
}

